def translate_name(name):
    result = name
    
    # Sort by length (longest first) to match longer phrases first
    sorted_trans = sorted(translations.items(), key=lambda x: len(x[0]), reverse=True)
    
    for eng, chn in sorted_trans:
        if eng.lower() in result.lower():
            pattern = re.compile(re.escape(eng), re.IGNORECASE)
            result = pattern.sub(chn, result)
    
    # Truncate to 15 chars if needed
    if len(result) > 15:
        result = result[:15]
    
    return result.strip()

# Process all items
items = []
for item in data['items']:
    short_name = translate_name(item['name'])
    items.append({
        'id': item['id'],
        'short_name': short_name
    })

# Write output
output = {
    'batch_id': data['batch_id'],
    'items': items
}

with open('processed_names.json', 'w', encoding='utf-8') as f:
    json.dump(output, f, ensure_ascii=False, indent=2)

print(f'Processed {len(items)} items successfully')