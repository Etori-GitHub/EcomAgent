// 型号/版本处理
function extractModel(name) {
  const patterns = [
    /(\d+)(?:st|nd|rd|th)?\s*(?:Generation|Gen|系列)?/gi,
    /\((\d+)(?:st|nd|rd|th)?\s*(?:Generation|Gen)?\)/gi,
    /Pro\s*Max/i,
    /Pro\s*Plus/i,
    /Pro/i,
    /Plus/i,
    /Max/i,
    /Mini/i,
    /Ultra/i,
    /SE\s*(\d+)?/i,
    /Series\s*(\d+)/i,
    /(\d+)K/i,
    /2\.0/i,
    /v(\d+)/i,
  ];
  
  for (const pattern of patterns) {
    const match = name.match(pattern);
    if (match) {
      const model = match[0];
      // 处理代数
      if (/(\d+)(?:st|nd|rd|th)?\s*(?:Generation|Gen)/i.test(model)) {
        const genMatch = model.match(/(\d+)/);
        if (genMatch) {
          return `${genMatch[1]}代`;
        }
      }
      // 处理SE
      if (/SE/i.test(model)) {
        const seMatch = model.match(/SE\s*(\d+)?/i);
        if (seMatch) {
          return seMatch[1] ? `SE${seMatch[1]}` : 'SE';
        }
      }
      // 处理Series
      if (/Series\s*(\d+)/i.test(model)) {
        const seriesMatch = model.match(/Series\s*(\d+)/i);
        if (seriesMatch) {
          return `Series ${seriesMatch[1]}`;
        }
      }
      // 处理K分辨率
      if (/(\d+)K/i.test(model)) {
        return model.toUpperCase();
      }
      return model;
    }
  }
  return '';
}

// 简化商品名称
function translateName(name) {
  if (!name || name.trim() === '') {
    return '';
  }
  
  // 清理特殊字符
  name = name.replace(/[®™©]/g, '');
  
  // 提取品牌
  let brand = '';
  let shortName = name;
  
  for (const [engBrand, cnBrand] of Object.entries(knownBrands)) {
    if (name.toLowerCase().startsWith(engBrand.toLowerCase())) {
      brand = cnBrand;
      shortName = name.substring(engBrand.length).trim();
      break;
    }
    // 检查品牌是否在名称中间
    const brandPattern = new RegExp(`\\b${engBrand}\\b`, 'i');
    if (brandPattern.test(name)) {
      brand = cnBrand;
      shortName = name.replace(brandPattern, '').trim();
      break;
    }
  }
  
  // 如果没有找到品牌，尝试从名称开头提取
  if (!brand) {
    const firstWord = name.split(/\s+/)[0];
    if (firstWord && firstWord.length > 2) {
      // 检查首字母大写的单词作为品牌
      if (/^[A-Z][a-z]+$/.test(firstWord)) {
        brand = firstWord;
        shortName = name.substring(firstWord.length).trim();
      }
    }
  }
  
  // 提取型号
  const model = extractModel(name);
  
  // 翻译产品类型
  let productType = '';
  for (const [engType, cnType] of Object.entries(productTypes)) {
    const typePattern = new RegExp(`\\b${engType}\\b`, 'i');
    if (typePattern.test(shortName)) {
      productType = cnType;
      shortName = shortName.replace(typePattern, '').trim();
      break;
    }
  }
  
  // 如果没有找到产品类型，使用剩余的短名称
  if (!productType) {
    // 提取核心产品词
    const words = shortName.split(/\s+/).filter(w => w.length > 0);
    if (words.length > 0) {
      // 取前几个有意义的词
      const meaningfulWords = words.filter(w => {
        // 过滤掉介词、冠词等
        const stopWords = ['with', 'for', 'and', 'the', 'a', 'an', 'in', 'on', 'at', 'to', 'of'];
        return !stopWords.includes(w.toLowerCase()) && w.length > 2;
      });
      
      if (meaningfulWords.length > 0) {
        productType = meaningfulWords.slice(0, 2).join(' ');
      } else {
        productType = words.slice(0, 2).join(' ');
      }
    }
  }
  
  // 组合最终名称
  let result = '';
  
  if (brand) {
    result += brand;
  }
  
  if (productType) {
    result += productType;
  }
  
  if (model) {
    result += ' ' + model;
  }
  
  // 清理结果
  result = result.replace(/\s+/g, ' ').trim();
  
  // 如果结果为空或太短，返回原始名称的前15个字符
  if (result.length < 3) {
    result = name.substring(0, 15).trim();
  }
  
  // 截断到15个字符
  if (result.length > 15) {
    result = result.substring(0, 15);
  }
  
  return result;
}

// 主函数
async function main() {
  const inputFile = path.join(__dirname, 'all_items.json');
  const outputFile = path.join(__dirname, 'processed_names.json');
  
  try {
    const data = JSON.parse(fs.readFileSync(inputFile, 'utf8'));
    
    const result = {
      batch_id: 'batch_' + new Date().toISOString().replace(/[:.]/g, '-'),
      items: []
    };
    
    for (const item of data) {
      if (item.name && item.name.trim() !== '') {
        const shortName = translateName(item.name);
        if (shortName) {
          result.items.push({
            id: item.id,
            short_name: shortName
          });
        }
      }
    }
    
    fs.writeFileSync(outputFile, JSON.stringify(result, null, 2), 'utf8');
    console.log(`翻译完成: ${result.items.length} 条`);
    console.log(`结果已保存到: ${outputFile}`);
  } catch (error) {
    console.error('处理失败:', error);
  }
}

main();
